"""Markdown tables for the momentum report from ``results.json``.

    python -I research/momentum/report.py OUT > OUT/tables.md
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

NAMES = ["M1", "M2", "M3", "M4"]
CALLOUT_YEARS = ["2015", "2016", "2018", "2020", "2022"]


def pct(value: float, digits: int = 1, sign: bool = False) -> str:
    return f"{value * 100:+.{digits}f}%" if sign else f"{value * 100:.{digits}f}%"


def num(value: float, digits: int = 2, sign: bool = False) -> str:
    return f"{value:+.{digits}f}" if sign else f"{value:.{digits}f}"


def pval(value: float) -> str:
    return "<0.0001" if value < 1e-4 else f"{value:.4f}"


def table(header: list[str], rows: list[list[str]], align: str | None = None) -> str:
    align = align or "|".join(["---"] + ["--:"] * (len(header) - 1))
    lines = ["| " + " | ".join(header) + " |", "|" + align + "|"]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def main(out_dir: Path) -> None:
    r = json.loads((out_dir / "results.json").read_text())
    v, b, c = r["variants"], r["benchmarks"], r["controls"]
    rd, pc, tests = r["random"], r["percentiles"], r["tests"]
    print("<!-- generated by research/momentum/report.py -->\n")

    print("### Headline (zero cost, and the $100,000 and $10,000 accounts after costs)\n")
    rows = []
    for name in NAMES:
        z, k100, k10 = v[name]["zero"], v[name]["100k"], v[name]["10k"]
        rows.append([f"**{name}**", pct(z["cagr"]), pct(k100["cagr"]), pct(k10["cagr"]), pct(z["max_dd"]),
                     num(z["sharpe"]), num(k100["sharpe"]), num(k10["sharpe"]), pct(z["vol"]),
                     f"{z['worst_year']['year']} {pct(z['worst_year']['return'], sign=True)}",
                     f"{z['worst_month_label']} {pct(z['worst_month'], sign=True)}",
                     f"{pc[name]['sharpe_pct']:.1f} / {pc[name]['cagr_pct']:.1f}"])
    for label, key in (("SPY buy-and-hold", "SPY"), ("RSP buy-and-hold", "RSP")):
        z, k100, k10 = b[key]["zero"], b[key]["100k"], b[key]["10k"]
        rows.append([label, pct(z["cagr"]), pct(k100["cagr"]), pct(k10["cagr"]), pct(z["max_dd"]),
                     num(z["sharpe"]), num(k100["sharpe"]), num(k10["sharpe"]), pct(z["vol"]),
                     f"{z['worst_year']['year']} {pct(z['worst_year']['return'], sign=True)}",
                     f"{z['worst_month_label']} {pct(z['worst_month'], sign=True)}", ""])
    a = c["all_members_zero"]
    rows.append([f"all members, equal weight (~{a['mean_names']:.0f} names)", pct(a["cagr"]), "n/a", "n/a",
                 pct(a["max_dd"]), num(a["sharpe"]), "n/a", "n/a", pct(a["vol"]),
                 f"{a['worst_year']['year']} {pct(a['worst_year']['return'], sign=True)}",
                 f"{a['worst_month_label']} {pct(a['worst_month'], sign=True)}", ""])
    rows.append(["random 20, median of 500", pct(rd["zero"]["cagr"]["p50"]), pct(rd["100k"]["cagr"]["p50"]),
                 pct(rd["10k"]["cagr"]["p50"]), pct(rd["zero"]["max_dd"]["p50"]), num(rd["zero"]["sharpe"]["p50"]),
                 num(rd["100k"]["sharpe"]["p50"]), num(rd["10k"]["sharpe"]["p50"]), pct(rd["zero"]["vol"]["p50"]),
                 "", "", ""])
    print(table(["", "CAGR 0 cost", "CAGR $100k", "CAGR $10k", "max DD (0 cost)", "Sharpe 0 cost",
                 "Sharpe $100k", "Sharpe $10k", "ann. vol", "worst year", "worst month",
                 "random-control percentile: Sharpe / CAGR"], rows))
    print()

    print("### Costs, turnover and account size\n")
    rows = []
    for name in NAMES:
        z = v[name]["zero"]
        rows.append([f"**{name}**", pct(z["turnover_month"]), num(z["entries_month"], 1),
                     pct(v[name]["100k"]["cost_year"]), pct(v[name]["10k"]["cost_year"]),
                     pct(v[name]["10k_resize_fee"]["cost_year"]), pct(v[name]["500"]["cost_year"]),
                     pct(z["cagr"] - v[name]["100k"]["cagr"]), pct(z["cagr"] - v[name]["10k"]["cagr"]),
                     f"{pct(v[name]['10k_resize_fee']['cagr'])} / {num(v[name]['10k_resize_fee']['sharpe'])}",
                     f"{pct(v[name]['500']['cagr'])} / {num(v[name]['500']['sharpe'])}"])
    for key, label in (("100k", "random 20 (median, $100k)"), ("10k", "random 20 (median, $10k)")):
        rows.append([label, pct(rd[key]["turnover_month"]["p50"]), num(rd[key]["entries_month"]["p50"], 1),
                     pct(rd["100k"]["cost_year"]["p50"]) if key == "100k" else "",
                     pct(rd["10k"]["cost_year"]["p50"]) if key == "10k" else "", "", "", "", "", "", ""])
    print(table(["", "one-way turnover / month", "names opened / month", "cost / year $100k", "cost / year $10k",
                 "cost / year $10k, resize pays $1", "cost / year $500 copy", "CAGR drag $100k", "CAGR drag $10k",
                 "$10k, resize pays $1: CAGR / Sharpe", "$500 copy: CAGR / Sharpe"], rows))
    print(f"\nSPY Sharpe on the $10,000 account: {num(b['SPY']['10k']['sharpe'], 3)} (zero cost "
          f"{num(b['SPY']['zero']['sharpe'], 3)}); RSP {num(b['RSP']['10k']['sharpe'], 3)}.\n")

    print("### Random control: 500 draws of 20 members a month\n")
    rows = []
    for key, label in (("zero", "zero cost"), ("100k", "$100,000"), ("10k", "$10,000")):
        for metric, fmt in (("cagr", pct), ("sharpe", num), ("max_dd", pct)):
            d = rd[key][metric]
            rows.append([f"{label}: {metric.replace('_', ' ')}", fmt(d["p5"]), fmt(d["p25"]), fmt(d["p50"]),
                         fmt(d["p75"]), fmt(d["p95"])])
    print(table(["", "5th", "25th", "50th", "75th", "95th"], rows))
    print()
    rows = [[f"**{name}**", num(v[name]["zero"]["sharpe"], 3), num(rd["zero"]["sharpe"]["p95"], 3),
             f"{pc[name]['sharpe_pct']:.1f}", pct(v[name]["zero"]["cagr"]), pct(rd["zero"]["cagr"]["p95"]),
             f"{pc[name]['cagr_pct']:.1f}", f"{pc[name]['sharpe_pct_100k']:.1f}", f"{pc[name]['sharpe_pct_10k']:.1f}"]
            for name in NAMES]
    print(table(["", "Sharpe (0 cost)", "random 95th", "percentile", "CAGR (0 cost)", "random 95th", "percentile",
                 "Sharpe percentile, $100k vs random $100k", "Sharpe percentile, $10k vs random $10k"], rows))
    f = r["random_with_m2_filter"]
    print(f"\nRandom 20 with M2's cash months (informational): median CAGR {pct(f['cagr']['p50'])}, "
          f"median Sharpe {num(f['sharpe']['p50'])}, 95th percentile Sharpe {num(f['sharpe']['p95'])}; "
          f"M2's percentile against it: {f['m2_sharpe_pct']:.1f} on Sharpe, {f['m2_cagr_pct']:.1f} on CAGR.\n")

    print("### Excess returns (monthly; mean shown annualised x12)\n")
    rows = []
    for family, label in (("vs_rsp_100k", "over RSP, $100k after costs (criterion 2)"),
                          ("vs_rsp_zero", "over RSP, zero cost"),
                          ("vs_rsp_10k", "over RSP, $10k after costs"),
                          ("vs_random_mean_zero", "over the random-control mean, zero cost")):
        for name in NAMES:
            t = tests[family][name]
            rows.append([label, name, pct(t["mean"], 2, True), pct(t["mean_annual"], 1, True), num(t["t"]),
                         num(t["nw_t"]), pval(t["p_one_sided"]), pval(t["holm_p"])])
    print(table(["series", "variant", "mean / month", "x12", "t", "Newey-West t (3)", "one-sided p", "Holm p"], rows,
                "---|---|--:|--:|--:|--:|--:|--:"))
    rm, am = r["random_mean_vs_rsp"], r["all_members_vs_rsp"]
    print(f"\nThe universe itself: random-control mean minus RSP {pct(rm['mean'] * 12, 1, True)} a year "
          f"(t {num(rm['t'])}); all members minus RSP {pct(am['mean'] * 12, 1, True)} (t {num(am['t'])}). "
          "Variant minus SPY ($100k): " + "; ".join(
              f"{name} {pct(r['vs_spy_100k'][name]['mean'] * 12, 1, True)} (t {num(r['vs_spy_100k'][name]['t'])})"
              for name in NAMES) + ".\n")

    print("### Pass/fail\n")
    rows = []
    spy10 = b["SPY"]["10k"]["sharpe"]
    for name in NAMES:
        vd = r["verdicts"][name]
        ok = lambda flag: "pass" if flag else "**fail**"  # noqa: E731
        rows.append([f"**{name}**",
                     f"{ok(vd['c1'])} ({num(v[name]['zero']['sharpe'], 3)} vs {num(rd['zero']['sharpe']['p95'], 3)})",
                     f"{ok(vd['c2'])} (Holm p {pval(tests['vs_rsp_100k'][name]['holm_p'])})",
                     f"{ok(vd['c3'])} ({num(v[name]['10k']['sharpe'], 3)} vs {num(spy10, 3)})",
                     "**PASS**" if vd["pass"] else "fail",
                     ok(vd["c3_conservative_costs"]),
                     " / ".join(ok(vd["in_index_universe"][k]) for k in ("c1", "c2", "c3"))])
    print(table(["variant", "(1) Sharpe > random 95th (0 cost)", "(2) excess over RSP, $100k, Holm p < 0.10",
                 "(3) $10k Sharpe >= SPY", "verdict", "(3) with resize fee", "already-in-index universe: (1) / (2) / (3)"],
                rows, "---|---|---|---|---|---|---"))
    print()

    print("### By calendar year (M1-M4 on the $100,000 account after costs; 2026 is Jan-Oct)\n")
    years = sorted(v["M1"]["100k"]["years"])
    series = [(name, v[name]["100k"]["years"]) for name in NAMES]
    series += [("random-control mean (0 cost)", c["random_mean_years"]), ("all members (0 cost)", a["years"]),
               ("SPY", b["SPY"]["zero"]["years"]), ("RSP", b["RSP"]["zero"]["years"])]
    header = [""] + [f"**{y}**" if y in CALLOUT_YEARS else y for y in years]
    rows = [[label] + [pct(values[y], 0, True) for y in years] for label, values in series]
    print(table(header, rows))
    print()
    rows = []
    for label, values in series:
        two = (1 + values["2015"]) * (1 + values["2016"]) - 1
        rows.append([label, pct(two, 1, True), pct(values["2018"], 1, True), pct(values["2020"], 1, True),
                     pct(values["2022"], 1, True), pct(values["2026"], 1, True)])
    print(table(["", "2015-16", "2018", "2020", "2022", "2026 (Jan-Oct)"], rows))
    print()

    print("### Momentum crashes: the five worst months against the random-control mean (zero cost)\n")
    rows = []
    for name in NAMES:
        cr = r["crashes"][name]
        for item in cr["worst_relative_months"]:
            rows.append([name, item["month"], pct(item["variant"], 1, True), pct(item["random_mean"], 1, True),
                         pct(item["excess"], 1, True)])
    print(table(["variant", "month", "variant", "random mean", "difference"], rows, "---|---|--:|--:|--:"))
    print()
    rows = [[name, pct(r["crashes"][name]["relative_drawdown"]["depth"]), r["crashes"][name]["relative_drawdown"]["peak_end"],
             r["crashes"][name]["relative_drawdown"]["trough_end"], str(r["crashes"][name]["relative_drawdown"]["recovered_by"])]
            for name in NAMES]
    print(table(["variant", "deepest fall relative to the random mean", "peak (month end)", "trough (month end)",
                 "back to the peak by"], rows, "---|--:|---|---|---"))
    print()
    rows = [[name, v[name]["zero"]["max_dd_peak"], v[name]["zero"]["max_dd_trough"], pct(v[name]["zero"]["max_dd"])]
            for name in NAMES]
    rows += [[key, b[key]["zero"]["max_dd_peak"], b[key]["zero"]["max_dd_trough"], pct(b[key]["zero"]["max_dd"])]
             for key in ("SPY", "RSP")]
    print(table(["", "max DD peak", "trough", "depth"], rows, "---|---|---|--:"))
    print()

    print("### Survivorship: stocks that were not yet in the index\n")
    dg = r["diagnostics"]
    rows = [[name, f"{dg[name]['position_months']}", pct(dg[name]["not_yet_in_index_share"]),
             pct(dg[name]["not_yet_in_index_mean_month_return"], 2, True), pct(dg[name]["in_index_mean_month_return"], 2, True),
             num(dg[name]["mean_names_kept"], 1), num(dg[name]["mean_largest_sector_count"], 1)] for name in NAMES]
    print(table(["variant", "position-months", "share not yet in the index", "their mean month",
                 "the rest's mean month", "names kept a month", "names in the largest sector"], rows))
    print(f"\nFor comparison, {pct(dg['eligible_not_yet_in_index_share'])} of all eligible stock-months, and "
          f"{pct(dg['random_not_yet_in_index_share'])} of the random control's, are in stocks not yet in the index.\n")
    alt = r["in_index_universe"]
    rows = []
    for name in NAMES:
        x = alt["variants"][name]
        rows.append([name, pct(x["zero"]["cagr"]), pct(x["10k"]["cagr"]), pct(x["zero"]["max_dd"]), num(x["zero"]["sharpe"]),
                     num(x["100k"]["sharpe"]), num(x["10k"]["sharpe"]), f"{x['sharpe_pct']:.1f}",
                     f"{pct(x['vs_rsp_100k']['mean_annual'], 1, True)} (t {num(x['vs_rsp_100k']['t'])}, Holm p {pval(x['vs_rsp_100k']['holm_p'])})",
                     f"{pct(x['vs_random_mean_zero']['mean_annual'], 1, True)} (t {num(x['vs_random_mean_zero']['t'])}, Holm p {pval(x['vs_random_mean_zero']['holm_p'])})"])
    ac = alt["controls"]
    rows.append(["random 20 (median)", pct(ac["random_zero"]["cagr"]["p50"]), "", pct(ac["random_zero"]["max_dd"]["p50"]),
                 num(ac["random_zero"]["sharpe"]["p50"]), "", "", f"95th: {num(ac['random_zero']['sharpe']['p95'])}", "", ""])
    rows.append(["all members (0 cost)", pct(ac["all_members_zero"]["cagr"]), "", pct(ac["all_members_zero"]["max_dd"]),
                 num(ac["all_members_zero"]["sharpe"]), "", "", "", "", ""])
    print(f"Already-in-index universe ({ac['eligible_first']} eligible in 2011-01, {ac['eligible_last']} in 2026-10):\n")
    print(table(["", "CAGR 0 cost", "CAGR $10k", "max DD", "Sharpe 0 cost", "Sharpe $100k", "Sharpe $10k",
                 "random Sharpe percentile", "excess over RSP, $100k (x12)", "excess over random mean (x12)"], rows))
    print()
    print("### Picks at three dates (M1-M4)\n")
    for name in NAMES:
        for month, picks in r["picks_examples"][name].items():
            print(f"* {name} {month}: {' '.join(picks)}")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
